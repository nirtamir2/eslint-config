export async function renderOxlintArtifacts(): Promise<Map<string, string>> {
  const data = await generateData();
  return new Map([
    [
      `${generatedDirectory}/compatibility-report.ts`,
      renderCompatibilityReport(data.report),
    ],
    [`${generatedDirectory}/fragments.ts`, renderFragments(data.fragments)],
    [
      `${generatedDirectory}/index.ts`,
      `${banner}export * from "./compatibility-report";\nexport * from "./fragments";\n`,
    ],
  ]);
}

async function listFiles(directory: string): Promise<Array<string>> {
  let entries;
  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw error;
  }

  const files = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);
      return entry.isDirectory() ? await listFiles(entryPath) : [entryPath];
    }),
  );
  return files.flat().toSorted((left, right) => left.localeCompare(right));
}

export function normalizeOxlintArtifactPath(relativePath: string): string {
  return relativePath.replaceAll(path.win32.sep, path.posix.sep);
}

export async function diffOxlintArtifacts(
  root: string,
  rendered: RenderedArtifacts,
): Promise<OxlintArtifactDiff> {
  const expectedFiles = [...rendered.keys()].toSorted((left, right) =>
    left.localeCompare(right),
  );
  const changed: Array<string> = [];
  const missing: Array<string> = [];

  for (const relativePath of expectedFiles) {
    try {
      const actual = await fs.readFile(path.join(root, relativePath), "utf8");
      if (actual !== rendered.get(relativePath)) changed.push(relativePath);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") {
        missing.push(relativePath);
        continue;
      }
      throw error;
    }
  }

  const actualFiles = await listFiles(path.join(root, generatedDirectory));
  const expected = new Set(expectedFiles);
  const unexpected = actualFiles
    .map((file) => normalizeOxlintArtifactPath(path.relative(root, file)))
    .filter((file) => !expected.has(file))
    .toSorted((left, right) => left.localeCompare(right));

  return { changed, missing, unexpected };
}

export async function writeOxlintArtifacts(
  root: string,
  rendered: RenderedArtifacts,
): Promise<void> {
  const diff = await diffOxlintArtifacts(root, rendered);
  await Promise.all(
    diff.unexpected.map((relativePath) =>
      fs.rm(path.join(root, relativePath), { force: true }),
    ),
  );

  for (const [relativePath, contents] of rendered) {
    const filePath = path.join(root, relativePath);
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    await fs.writeFile(filePath, contents);
  }
}

export function hasOxlintArtifactDiff(diff: OxlintArtifactDiff): boolean {
  return (
    diff.changed.length > 0 ||
    diff.missing.length > 0 ||
    diff.unexpected.length > 0
  );
}

export function formatOxlintArtifactDiff(diff: OxlintArtifactDiff): string {
  const lines = ["Generated Oxlint artifacts are out of date."];
  for (const file of diff.changed) lines.push(`  changed: ${file}`);
  for (const file of diff.missing) lines.push(`  missing: ${file}`);
  for (const file of diff.unexpected) lines.push(`  unexpected: ${file}`);
  lines.push("Run `pnpm generate:oxlint` and commit the result.");
  return lines.join("\n");
}
