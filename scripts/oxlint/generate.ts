async function migrateSource(
  source: Array<TypedFlatConfigItem>,
  reporter: MigrationReporter,
  options: MigrateSourceOptions = {},
): Promise<OxlintConfig> {
  const {
    defaultRuleFiles,
    stripBaseline = true,
    typeAware = false,
  } = options;
  const prepared = prepareMigrationSource(source, defaultRuleFiles);
  const migrated = await migrate(prepared.configs, undefined, {
    jsPlugins: false,
    reporter,
    typeAware,
    withNursery: false,
  });
  const restored = restoreMigrationScopes(migrated, prepared.scopes);
  return normalizeOxlintConfig(restored, stripBaseline);
}

function variantCompatibility(
  config: OxlintConfig,
  reporter: MigrationReporter,
  sources: Array<string>,
): VariantCompatibility {
  const skippedRules = reporter.getSkippedRulesByCategory();
  const isPartial = Object.values(skippedRules).some(
    (rules) => rules.length > 0,
  );
  return {
    migratedRuleCount: countConfiguredRules(config),
    skippedRules,
    sources: [...sources],
    status: isPartial ? "partial" : "supported",
    warnings: reporter.getWarnings(),
  };
}

async function generateBase(
  isInEditor: boolean,
): Promise<{ config: OxlintConfig; compatibility: VariantCompatibility }> {
  const reporter = new MigrationReporter();
  const sourceUnits = [
    ["ignores", await ignores()],
    ["javascript", await javascript({ isInEditor })],
    ["comments", await comments()],
    ["node", await node()],
    ["imports", await imports({ stylistic: false })],
  ] as const;
  const migratedUnits: Array<OxlintConfig> = [];

  for (const [, source] of sourceUnits) {
    migratedUnits.push(
      await migrateSource(source, reporter, { stripBaseline: false }),
    );
  }

  const config = mergeOxlintConfigs(migratedUnits);
  return {
    compatibility: variantCompatibility(
      config,
      reporter,
      sourceUnits.map(([name]) => name),
    ),
    config,
  };
}

async function generateFragment(
  options: GenerateFragmentOptions,
): Promise<{
  compatibility: VariantCompatibility;
  fragment: GeneratedFragmentData;
}> {
  const {
    defaultRuleFiles,
    source,
    sourceName,
    typeAware = false,
  } = options;
  const overrideTarget = options.overrideTarget ?? { files: defaultRuleFiles };
  const reporter = new MigrationReporter();
  const config = await migrateSource(source, reporter, {
    defaultRuleFiles,
    typeAware,
  });

  return {
    compatibility: variantCompatibility(config, reporter, [sourceName]),
    fragment: {
      config,
      overrideTarget: {
        ...overrideTarget,
        ...(overrideTarget?.excludeFiles == null
          ? {}
          : {
              excludeFiles: translateOxlintGlobs(
                overrideTarget.excludeFiles,
              ),
            }),
        files: translateOxlintGlobs(
          overrideTarget?.files ?? defaultRuleFiles,
        ),
      },
    },
  };
}

async function readPackageVersion(url: URL): Promise<string> {
  const packageJson = JSON.parse(await fs.readFile(url, "utf8")) as {
    version?: unknown;
  };
  if (typeof packageJson.version !== "string") {
    throw new TypeError(`Package at ${url.pathname} has no string version`);
  }
  return packageJson.version;
}

