async function generateData(): Promise<GeneratedData> {
  const variants: Record<string, VariantCompatibility> = {};

  const baseDefault = await generateBase(false);
  variants["base.default"] = baseDefault.compatibility;
  const baseEditor = await generateBase(true);
  variants["base.editor"] = baseEditor.compatibility;

  const unicornAllRecommended = await generateFragment({
    defaultRuleFiles: [GLOB_SRC],
    source: await unicorn({ allRecommended: true }),
    sourceName: "unicorn",
  });
  variants["unicorn.allRecommended"] =
    unicornAllRecommended.compatibility;
  const unicornSelected = await generateFragment({
    defaultRuleFiles: [GLOB_SRC],
    source: await unicorn({ allRecommended: false }),
    sourceName: "unicorn",
  });
  variants["unicorn.selected"] = unicornSelected.compatibility;

  const jsxFragment = await generateFragment({
    defaultRuleFiles: [GLOB_JSX, GLOB_TSX],
    source: await jsx(),
    sourceName: "jsx",
  });
  variants.jsx = jsxFragment.compatibility;

  const typescriptAppStandard = await generateFragment({
    defaultRuleFiles: [GLOB_TS, GLOB_TSX],
    source: await typescript({ erasableOnly: true, type: "app" }),
    sourceName: "typescript",
  });
  variants["typescript.app.standard"] =
    typescriptAppStandard.compatibility;
  const typescriptAppTypeAware = await generateFragment({
    defaultRuleFiles: [GLOB_TS, GLOB_TSX],
    source: await typescript({
      erasableOnly: true,
      tsconfigPath: "tsconfig.json",
      type: "app",
    }),
    sourceName: "typescript",
    typeAware: true,
  });
  variants["typescript.app.typeAware"] =
    typescriptAppTypeAware.compatibility;
  const typescriptLibStandard = await generateFragment({
    defaultRuleFiles: [GLOB_TS, GLOB_TSX],
    source: await typescript({ erasableOnly: true, type: "lib" }),
    sourceName: "typescript",
  });
  variants["typescript.lib.standard"] =
    typescriptLibStandard.compatibility;
  const typescriptLibTypeAware = await generateFragment({
    defaultRuleFiles: [GLOB_TS, GLOB_TSX],
    source: await typescript({
      erasableOnly: true,
      tsconfigPath: "tsconfig.json",
      type: "lib",
    }),
    sourceName: "typescript",
    typeAware: true,
  });
  variants["typescript.lib.typeAware"] =
    typescriptLibTypeAware.compatibility;

  const testDefault = await generateFragment({
    defaultRuleFiles: GLOB_TESTS,
    source: await test({ isInEditor: false }),
    sourceName: "test",
  });
  variants["test.default"] = testDefault.compatibility;
  const testEditor = await generateFragment({
    defaultRuleFiles: GLOB_TESTS,
    source: await test({ isInEditor: true }),
    sourceName: "test",
  });
  variants["test.editor"] = testEditor.compatibility;

  const vueJavaScript = await generateFragment({
    defaultRuleFiles: [GLOB_VUE],
    source: await vue({
      a11y: false,
      sfcBlocks: false,
      stylistic: false,
      typescript: false,
    }),
    sourceName: "vue",
  });
  variants["vue.javascript"] = vueJavaScript.compatibility;
  const vueTypeScript = await generateFragment({
    defaultRuleFiles: [GLOB_VUE],
    source: await vue({
      a11y: false,
      sfcBlocks: false,
      stylistic: false,
      typescript: true,
    }),
    sourceName: "vue",
  });
  variants["vue.typescript"] = vueTypeScript.compatibility;

  const neutralReactEnvironment = { hasPackage: () => false };
  const reactStandard = await generateFragment({
    defaultRuleFiles: [GLOB_SRC],
    source: await react({}, neutralReactEnvironment),
    sourceName: "react",
  });
  variants["react.standard"] = reactStandard.compatibility;
  const reactTypeAware = await generateFragment({
    defaultRuleFiles: [GLOB_SRC],
    source: await react(
      { tsconfigPath: "tsconfig.json" },
      neutralReactEnvironment,
    ),
    sourceName: "react",
    typeAware: true,
  });
  variants["react.typeAware"] = reactTypeAware.compatibility;

  const nextjsFragment = await generateFragment({
    defaultRuleFiles: [GLOB_SRC],
    source: await nextjs(),
    sourceName: "nextjs",
  });
  variants.nextjs = nextjsFragment.compatibility;
  const jsdocFragment = await generateFragment({
    defaultRuleFiles: [GLOB_SRC],
    source: await jsdoc({ stylistic: false }),
    sourceName: "jsdoc",
  });
  variants.jsdoc = jsdocFragment.compatibility;

  const [migrateVersion, oxlintVersion] = await Promise.all([
    readPackageVersion(
      new URL("../../node_modules/@oxlint/migrate/package.json", import.meta.url),
    ),
    readPackageVersion(
      new URL("../../node_modules/oxlint/package.json", import.meta.url),
    ),
  ]);

  return {
    fragments: {
      base: {
        default: baseDefault.config,
        editor: baseEditor.config,
      },
      unicorn: {
        allRecommended: unicornAllRecommended.fragment,
        selected: unicornSelected.fragment,
      },
      jsx: jsxFragment.fragment,
      typescript: {
        app: {
          standard: typescriptAppStandard.fragment,
          typeAware: typescriptAppTypeAware.fragment,
        },
        lib: {
          standard: typescriptLibStandard.fragment,
          typeAware: typescriptLibTypeAware.fragment,
        },
      },
      test: {
        default: testDefault.fragment,
        editor: testEditor.fragment,
      },
      vue: {
        javascript: vueJavaScript.fragment,
        typescript: vueTypeScript.fragment,
      },
      react: {
        standard: reactStandard.fragment,
        typeAware: reactTypeAware.fragment,
      },
      nextjs: nextjsFragment.fragment,
      jsdoc: jsdocFragment.fragment,
    },
    report: {
      generation: {
        jsPlugins: false,
        typeAware: "per-variant",
        withNursery: false,
      },
      limitations: compatibilityLimitations(),
      schemaVersion: 1,
      variants,
      versions: {
        migrate: migrateVersion,
        oxlint: oxlintVersion,
      },
    },
  };
}

